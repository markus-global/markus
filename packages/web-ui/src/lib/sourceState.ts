/**
 * 一次取数的**读取状态**。只有三种，且必须三分：
 *
 *  · `loading` —— 还不知道（在飞）
 *  · `ok`      —— 读到了，内容（哪怕是空列表）是事实
 *  · `error`   —— 读失败了，**这不是「没有」**
 *
 * 为什么单独成一个模块而不是就地写字面量：这是「失败 ≠ 空」这条纪律的类型载体。
 * 一旦允许各处各写一遍联合类型，就一定会出现把失败折成 `items: []` 的写法 ——
 * 界面上表现为「明明有数据却显示空」，且没有任何报错。
 */
export type SourceState = 'loading' | 'ok' | 'error';
