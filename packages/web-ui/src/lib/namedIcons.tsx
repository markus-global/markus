export function hasNamedIcon(name?: string | null): boolean {
  return !!name && name in NAMED_ICONS;
}

/** Render a named icon as an inline SVG. Returns null for unknown names. */
export function NamedIcon({ name, size = 24, className = '' }: { name: string; size?: number; className?: string }) {
  const node = NAMED_ICONS[name];
  if (!node) return null;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden
    >
      {node}
    </svg>
  );
}

